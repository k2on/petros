//! Refuse a change to an app's mutations that the log cannot survive.
//!
//! The log is permanent: every entry ever written is replayed by every peer
//! forever. So a verb may be added and an argument may be added, but a verb may
//! never be removed or renamed and an argument may never be dropped or retyped.
//! That rule used to live in a contributing guide, where it held right up until
//! somebody was busy.
//!
//! This makes it a comparison. A snapshot of the mutations a release shipped is
//! checked in beside the domain; every build compares itself against it and
//! fails on anything the log cannot absorb. The snapshot is plain text, so the
//! diff in a review *is* the change to the log's surface.
//!
//! ```text
//! log-compat <module.wasm> <snapshot>           # check, and fail on a break
//! log-compat <module.wasm> <snapshot> --write   # record what this build declares
//! ```
//!
//! Reading the schema out of the built module rather than the source is
//! deliberate: what ships is what is checked, and there is no second definition
//! to drift.

use std::process::ExitCode;

use petros_schema::compat;

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let (Some(wasm), Some(snapshot)) = (args.next(), args.next()) else {
        eprintln!("usage: log-compat <module.wasm> <snapshot> [--write]");
        return ExitCode::FAILURE;
    };
    let write = args.any(|a| a == "--write");

    let bytes = match std::fs::read(&wasm) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("log-compat: cannot read {wasm}: {e}");
            return ExitCode::FAILURE;
        }
    };
    let now = match petros_schema::from_wasm(&bytes) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("log-compat: {wasm} carries no readable schema: {e}");
            return ExitCode::FAILURE;
        }
    };

    if write {
        let body = format!("{HEADER}{}", compat::to_text(&now));
        if let Err(e) = std::fs::write(&snapshot, body) {
            eprintln!("log-compat: cannot write {snapshot}: {e}");
            return ExitCode::FAILURE;
        }
        println!("log-compat: wrote {snapshot} ({} verbs)", now.verbs.len());
        return ExitCode::SUCCESS;
    }

    // A missing snapshot is not a pass. An app that has never recorded one has
    // nothing to be held to, and saying so is more useful than saying nothing.
    let text = match std::fs::read_to_string(&snapshot) {
        Ok(t) => t,
        Err(e) => {
            eprintln!(
                "log-compat: cannot read {snapshot}: {e}\n\
                 Record what this build declares with `--write`, commit it, and \
                 every build after this one is held to it."
            );
            return ExitCode::FAILURE;
        }
    };
    let was = match compat::from_text(&text) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("log-compat: {snapshot} is not readable: {e}");
            return ExitCode::FAILURE;
        }
    };

    let breaks = compat::breaking_changes(&was, &now);
    if breaks.is_empty() {
        // Said out loud, because a check that only speaks when it fails leaves
        // you wondering whether it ran.
        println!(
            "log-compat: {} verbs, compatible with {snapshot}",
            now.verbs.len()
        );
        return ExitCode::SUCCESS;
    }

    eprintln!(
        "log-compat: {} change{} the log cannot survive:\n",
        breaks.len(),
        if breaks.len() == 1 { "" } else { "s" }
    );
    for b in &breaks {
        eprintln!("  - {b}\n");
    }
    eprintln!(
        "Entries already written are replayed by every peer, on every device, \
         forever.\nIf this really is what you want — a log nobody has yet, a \
         name nobody has shipped —\nrerun with `--write` to record the new \
         surface deliberately."
    );
    ExitCode::FAILURE
}

const HEADER: &str = "\
# The mutations this app's log carries. Generated by `--write`; checked on every
# build. A verb or an argument may be ADDED — a payload without a field decodes
# to that field's default. Removing or renaming a verb, or dropping or retyping
# an argument, breaks every entry already written, and the check refuses it.
";
